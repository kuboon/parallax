import type { RemixNode } from "remix/ui";

import { base } from "../lib/base.ts";
import { Link } from "../lib/link.tsx";

export const title = "仕組み — Facebook パララックス画像シミュレータ";
export const description =
  "縦ストライプの合成画像とジグザグ深度マップが、なぜレンチキュラーのように振る舞うのか。波形の選び方、必要な視差量、そして深度マップの渡し方。";

export default function HowItWorks(): RemixNode {
  return (
    <>
      <h1>仕組み</h1>

      <h2>パララックス表示がしていること</h2>
      <p>
        画像と深度マップを渡された表示側は、見る角度に応じて画素を横にずらします。
        手前（深度が大きい）ほど大きく、奥ほど小さく。重なった場所では手前が勝ちます。
        Facebook の実装は公開されていないので、このシミュレータもその 2
        つの規則だけを実装しています。 ずらし量が深度 1
        階調あたり何ピクセルになるのかは分からないので、
        <strong>ゲイン</strong>という自由変数として置いてあります。
      </p>

      <h2>なぜジグザグなのか</h2>
      <p>
        深度が列ごとに一定の割合で増える区間では、ずらし量も一定の割合で増えます。
        つまりその区間は <code>1 + ゲイン × 傾き</code>{" "}
        倍に引き伸ばされる、ただのアフィン変換です。
        傾きが正なら広がり、負なら縮みます。
      </p>
      <p>
        そこでストライプ A の上で深度を上げ、ストライプ B
        の上で同じ傾きで下げます。 これが三角波です。すると A と B
        は必ず逆向きに拡縮するので、
        <code>ゲイン × 傾き</code> が 1 に達したところで
        <strong>A は 2 倍に広がり、B は幅 0 に潰れる</strong>——A
        が対を丸ごと覆います。
        反対側の角度では役割が入れ替わります。これはレンチキュラー印刷そのものです。
      </p>
      <p>
        三角波の傾きはストライプ幅 <code>w</code> にわたって深度の全域を登るので
        {" "}
        <code>255 / w</code>、必要な視差量は <code>w</code>{" "}
        ピクセルになります。
        コントラストを下げて使う階調を狭めれば、その分だけ多くの視差が要ります。
      </p>

      <h2>他の波形</h2>
      <ul>
        <li>
          <strong>のこぎり波</strong>は対の全体で 1
          回だけ登り、境界で不連続に落ちます。
          必要な視差量は倍。切り替わりはしますが、段差のところで穴が空きます。
        </li>
        <li>
          <strong>矩形波</strong>には傾きがありません。伸び縮みは起きず、
          手前のストライプが奥のストライプの上を滑っていくだけです。滑った跡は穴になります。
        </li>
        <li>
          <strong>正弦波</strong>は三角波の角を丸めたもの。
          深度マップが平滑化されて届く場合に近い形なので、比較用に入れてあります。
        </li>
      </ul>

      <h2>ぴったりの視差量、の少し先</h2>
      <p>
        以上は連続の話で、実際の画素は連続ではありません。ちょうどの視差量では、
        閉じるはずのストライプが 1 周期あたり 1 列だけ残ります。 そこから 1.5
        倍ほど踏み込むと、隣の伸びたストライプがその列を覆い、深度バッファがそれを保ちます。
        シミュレータの「合わせる」ボタンはこの 1.5 倍を入れます。
      </p>

      <h2>深度マップの渡し方</h2>
      <p>2 通り用意してあります。</p>
      <ul>
        <li>
          <strong>2 ファイル</strong>——<code>名前.jpg</code> と{" "}
          <code>名前_depth.jpg</code>。
          この命名で組にして投稿する方法が、以前から知られています。
        </li>
        <li>
          <strong>1 ファイル</strong>——<code>GDepth</code>{" "}
          XMP。深度マップを base64 にして JPEG のマーカーセグメントに入れる、
          Google カメラ由来の形式です。1 セグメントには収まらないので、 XMP の
          Extended 機構で分割し、MD5 で束ねています。
        </li>
      </ul>
      <p>
        どちらが今の Facebook
        に通るのかは、上げてみないと分かりません。それがこのツールの目的です。
      </p>

      <h2>再エンコードという敵</h2>
      <p>
        投稿された画像は縮小され、JPEG
        で再圧縮されます。ストライプの縞はまさにその過程で捨てられる高周波です。
        深度マップも同様に、あるいはもっと粗く扱われるかもしれません。
        シミュレータの「深度マップのぼかし」は、そうなったときにどこまで縞が生き残るかを見るためのものです。
        上げていくと、ある太さから先は何も起きなくなります。
      </p>

      <p>
        <Link class="button" href={base === "" ? "/" : base}>
          シミュレータに戻る →
        </Link>
      </p>
    </>
  );
}
